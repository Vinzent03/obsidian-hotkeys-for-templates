import esbuild from "esbuild";

const prod = process.argv[2] === "production";

const context = await esbuild.context({
    banner: {
        js: "/* Generated by esbuild. Source: https://github.com/Vinzent03/obsidian-hotkeys-for-templates */",
    },
    entryPoints: ["src/main.ts"],
    bundle: true,
    external: ["obsidian"],
    format: "cjs",
    target: "es2021",
    logLevel: "info",
    sourcemap: prod ? false : "inline",
    treeShaking: true,
    platform: "browser",
    minify: prod,
    outfile: "main.js",
});

if (prod) {
    try {
        await context.rebuild();
    } finally {
        await context.dispose();
    }
} else {
    await context.watch();
}
